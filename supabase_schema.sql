-- 4.1. دالة RPC موحدة لإنشاء وتأكيد أي مستخدم في auth.users و profiles مباشرة
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.admin_create_auth_user(
    p_email TEXT,
    p_password TEXT,
    p_username TEXT,
    p_name TEXT,
    p_phone TEXT,
    p_role TEXT
)
RETURNS UUID AS $$
DECLARE
    new_user_id UUID;
BEGIN
    SELECT id INTO new_user_id FROM auth.users WHERE email = p_email LIMIT 1;
    
    IF new_user_id IS NOT NULL THEN
        UPDATE auth.users 
        SET encrypted_password = crypt(p_password, gen_salt('bf')),
            raw_user_meta_data = jsonb_build_object('username', p_username, 'name', p_name, 'phone', p_phone, 'role', p_role),
            email_confirmed_at = COALESCE(email_confirmed_at, NOW()),
            updated_at = NOW()
        WHERE id = new_user_id;
    ELSE
        new_user_id := gen_random_uuid();
        INSERT INTO auth.users (
            id,
            instance_id,
            email,
            encrypted_password,
            email_confirmed_at,
            raw_app_meta_data,
            raw_user_meta_data,
            created_at,
            updated_at,
            role,
            aud
        ) VALUES (
            new_user_id,
            '00000000-0000-0000-0000-000000000000',
            p_email,
            crypt(p_password, gen_salt('bf')),
            NOW(),
            '{"provider":"email","providers":["email"]}'::jsonb,
            jsonb_build_object('username', p_username, 'name', p_name, 'phone', p_phone, 'role', p_role),
            NOW(),
            NOW(),
            'authenticated',
            'authenticated'
        );
    END IF;

    -- إضافة أو تحديث البروفايل بنفس المعرف id و user_id
    INSERT INTO public.profiles (id, user_id, username, email, name, phone, role, status, permissions)
    VALUES (
        new_user_id,
        new_user_id,
        p_username,
        p_email,
        p_name,
        p_phone,
        p_role,
        'active',
        CASE 
            WHEN p_role = 'admin' THEN '{"manage_students": true, "manage_sheikhs": true, "manage_admins": true, "daily_recitation": true, "manage_exams": true, "print_reports": true, "honor_board": true, "center_settings": true, "manage_accounts": true, "archive_season": true}'::jsonb
            WHEN p_role = 'sheikh' THEN '{"manage_students": false, "manage_sheikhs": false, "manage_admins": false, "daily_recitation": true, "manage_exams": true, "print_reports": true, "honor_board": true, "center_settings": false, "manage_accounts": false, "archive_season": false}'::jsonb
            WHEN p_role = 'data_entry' THEN '{"manage_students": true, "manage_sheikhs": false, "manage_admins": false, "daily_recitation": true, "manage_exams": true, "print_reports": true, "honor_board": true, "center_settings": false, "manage_accounts": false, "archive_season": false}'::jsonb
            ELSE '{"manage_students": false, "manage_sheikhs": false, "manage_admins": false, "daily_recitation": false, "manage_exams": false, "print_reports": false, "honor_board": false, "center_settings": false, "manage_accounts": false, "archive_season": false}'::jsonb
        END
    )
    ON CONFLICT (id) DO UPDATE SET
        user_id = EXCLUDED.user_id,
        username = EXCLUDED.username,
        email = EXCLUDED.email,
        name = EXCLUDED.name,
        phone = EXCLUDED.phone,
        role = EXCLUDED.role;

    RETURN new_user_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

