-- ==============================================================================
-- 4. مشغل (Trigger) للربط التلقائي الفوري بين auth.users و public.profiles
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
    v_username TEXT;
    v_name TEXT;
    v_phone TEXT;
    v_role TEXT;
BEGIN
    v_username := COALESCE(NEW.raw_user_meta_data->>'username', split_part(NEW.email, '@', 1));
    v_name := COALESCE(NEW.raw_user_meta_data->>'name', 'مستخدم جديد');
    v_phone := COALESCE(NEW.raw_user_meta_data->>'phone', '');
    v_role := COALESCE(NEW.raw_user_meta_data->>'role', 'parent');

    -- إذا كان اسم المستخدم مستخدماً في بروفايل آخر، يتم إضافة تمييز فريد له
    IF EXISTS (SELECT 1 FROM public.profiles WHERE username = v_username AND id <> NEW.id) THEN
        v_username := v_username || '_' || substr(replace(NEW.id::text, '-', ''), 1, 4);
    END IF;

    INSERT INTO public.profiles (id, user_id, username, email, name, phone, role, status, permissions)
    VALUES (
        NEW.id,
        NEW.id,
        v_username,
        NEW.email,
        v_name,
        v_phone,
        v_role,
        'active',
        CASE 
            WHEN v_role = 'admin' THEN '{
                "manage_students": true, "manage_sheikhs": true, "manage_admins": true, "daily_recitation": true, "manage_exams": true, "print_reports": true, "honor_board": true, "center_settings": true, "manage_accounts": true, "archive_season": true
            }'::jsonb
            WHEN v_role = 'sheikh' THEN '{
                "manage_students": false, "manage_sheikhs": false, "manage_admins": false, "daily_recitation": true, "manage_exams": true, "print_reports": true, "honor_board": true, "center_settings": false, "manage_accounts": false, "archive_season": false
            }'::jsonb
            WHEN v_role = 'data_entry' THEN '{
                "manage_students": true, "manage_sheikhs": false, "manage_admins": false, "daily_recitation": true, "manage_exams": true, "print_reports": true, "honor_board": true, "center_settings": false, "manage_accounts": false, "archive_season": false
            }'::jsonb
            ELSE '{
                "manage_students": false, "manage_sheikhs": false, "manage_admins": false, "daily_recitation": false, "manage_exams": false, "print_reports": false, "honor_board": false, "center_settings": false, "manage_accounts": false, "archive_season": false
            }'::jsonb
        END
    )
    ON CONFLICT (id) DO UPDATE SET
        user_id = EXCLUDED.user_id,
        username = EXCLUDED.username,
        email = EXCLUDED.email,
        name = EXCLUDED.name,
        phone = EXCLUDED.phone,
        role = EXCLUDED.role;

    RETURN NEW;
EXCEPTION WHEN OTHERS THEN
    -- حماية التسجيل من الانهيار
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

