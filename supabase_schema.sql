-- ==============================================================================
-- 7. جدول الطلاب (students)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    civil_id TEXT NOT NULL,
    dob DATE,
    age INT NOT NULL DEFAULT 10,
    grade TEXT NOT NULL DEFAULT 'المتوسط',
    parent_name TEXT,
    parent_phone TEXT NOT NULL,
    parent_email TEXT NOT NULL DEFAULT '',
    parent_username TEXT,
    sheikh_id BIGINT REFERENCES public.sheikhs(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
    join_date DATE NOT NULL DEFAULT CURRENT_DATE,
    current_juz INT NOT NULL DEFAULT 1,
    target_juz INT NOT NULL DEFAULT 5,
    points INT NOT NULL DEFAULT 100,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ==============================================================================
-- 8. جدول سجلات التسميع اليومي والمتابعة (tracking)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.tracking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    sheikh_id BIGINT REFERENCES public.sheikhs(id) ON DELETE SET NULL,
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    new_surah TEXT,
    new_from INT,
    new_to INT,
    rev_surah TEXT,
    rev_from INT,
    rev_to INT,
    big_rev_surah TEXT,
    big_rev_from INT,
    big_rev_to INT,
    att TEXT NOT NULL DEFAULT 'حضوري',
    eval TEXT NOT NULL DEFAULT 'ممتاز',
    notes TEXT,
    status TEXT NOT NULL DEFAULT 'approved' CHECK (status IN ('draft', 'approved')),
    read_by_parent BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ==============================================================================
-- 9. جدول ملاحظات المشايخ لأولياء الأمور (notes)
-- ==============================================================================
