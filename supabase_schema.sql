-- ==============================================================================
-- 3. جدول الحسابات والمستخدمين والصلاحيات (profiles) المرتبط بـ auth.users
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    phone TEXT,
    role TEXT NOT NULL CHECK (role IN ('admin', 'sheikh', 'parent', 'data_entry')),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    permissions JSONB NOT NULL DEFAULT '{"manage_students": false}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ==============================================================================
-- 4. مشغل (Trigger) للربط التلقائي الفوري بين auth.users و public.profiles
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
    v_username TEXT;
    v_name TEXT;
    v_phone TEXT;
    v_role TEXT;
BEGIN
    v_username := COALESCE(NEW.raw_user_meta_data->>'username', split_part(NEW.email, '@', 1));
    v_name := COALESCE(NEW.raw_user_meta_data->>'name', 'مستخدم جديد');
    v_phone := COALESCE(NEW.raw_user_meta_data->>'phone', '');
    v_role := COALESCE(NEW.raw_user_meta_data->>'role', 'parent');

    IF EXISTS (SELECT 1 FROM public.profiles WHERE username = v_username AND id <> NEW.id) THEN
        v_username := v_username || '_' || substr(replace(NEW.id::text, '-', ''), 1, 4);
    END IF;

    INSERT INTO public.profiles (id, user_id, username, email, name, phone, role, status, permissions)
    VALUES (
        NEW.id, NEW.id, v_username, NEW.email, v_name, v_phone, v_role, 'active',
        CASE 
            WHEN v_role = 'admin' THEN '{"manage_students": true, "manage_sheikhs": true, "manage_admins": true, "daily_recitation": true, "manage_exams": true, "print_reports": true, "honor_board": true, "center_settings": true, "manage_accounts": true, "archive_season": true}'::jsonb
            WHEN v_role = 'sheikh' THEN '{"manage_students": false, "manage_sheikhs": false, "manage_admins": false, "daily_recitation": true, "manage_exams": true, "print_reports": true, "honor_board": true, "center_settings": false, "manage_accounts": false, "archive_season": false}'::jsonb
            WHEN v_role = 'data_entry' THEN '{"manage_students": true, "manage_sheikhs": false, "manage_admins": false, "daily_recitation": true, "manage_exams": true, "print_reports": true, "honor_board": true, "center_settings": false, "manage_accounts": false, "archive_season": false}'::jsonb
            ELSE '{"manage_students": false, "manage_sheikhs": false, "manage_admins": false, "daily_recitation": false, "manage_exams": false, "print_reports": false, "honor_board": false, "center_settings": false, "manage_accounts": false, "archive_season": false}'::jsonb
        END
    )
    ON CONFLICT (id) DO UPDATE SET
        user_id = EXCLUDED.user_id, username = EXCLUDED.username, email = EXCLUDED.email, name = EXCLUDED.name, phone = EXCLUDED.phone, role = EXCLUDED.role;

    RETURN NEW;
EXCEPTION WHEN OTHERS THEN
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- ==============================================================================
-- 4.1. دالة RPC موحدة لإنشاء وتأكيد أي مستخدم في auth.users و profiles مباشرة
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.admin_create_auth_user(
    p_email TEXT, p_password TEXT, p_username TEXT, p_name TEXT, p_phone TEXT, p_role TEXT
)
RETURNS UUID AS $$
DECLARE
    new_user_id UUID;
BEGIN
    SELECT id INTO new_user_id FROM auth.users WHERE email = p_email LIMIT 1;
    
    IF new_user_id IS NOT NULL THEN
        UPDATE auth.users 
        SET encrypted_password = crypt(p_password, gen_salt('bf')),
            raw_user_meta_data = jsonb_build_object('username', p_username, 'name', p_name, 'phone', p_phone, 'role', p_role),
            email_confirmed_at = COALESCE(email_confirmed_at, NOW()), updated_at = NOW()
        WHERE id = new_user_id;
    ELSE
        new_user_id := gen_random_uuid();
        INSERT INTO auth.users (id, instance_id, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, role, aud) 
        VALUES (new_user_id, '00000000-0000-0000-0000-000000000000', p_email, crypt(p_password, gen_salt('bf')), NOW(), '{"provider":"email","providers":["email"]}'::jsonb, jsonb_build_object('username', p_username, 'name', p_name, 'phone', p_phone, 'role', p_role), NOW(), NOW(), 'authenticated', 'authenticated');
    END IF;

    INSERT INTO public.profiles (id, user_id, username, email, name, phone, role, status, permissions)
    VALUES (new_user_id, new_user_id, p_username, p_email, p_name, p_phone, p_role, 'active',
        CASE 
            WHEN p_role = 'admin' THEN '{"manage_students": true, "manage_sheikhs": true, "manage_admins": true, "daily_recitation": true, "manage_exams": true, "print_reports": true, "honor_board": true, "center_settings": true, "manage_accounts": true, "archive_season": true}'::jsonb
            WHEN p_role = 'sheikh' THEN '{"manage_students": false, "manage_sheikhs": false, "manage_admins": false, "daily_recitation": true, "manage_exams": true, "print_reports": true, "honor_board": true, "center_settings": false, "manage_accounts": false, "archive_season": false}'::jsonb
            WHEN p_role = 'data_entry' THEN '{"manage_students": true, "manage_sheikhs": false, "manage_admins": false, "daily_recitation": true, "manage_exams": true, "print_reports": true, "honor_board": true, "center_settings": false, "manage_accounts": false, "archive_season": false}'::jsonb
            ELSE '{"manage_students": false, "manage_sheikhs": false, "manage_admins": false, "daily_recitation": false, "manage_exams": false, "print_reports": false, "honor_board": false, "center_settings": false, "manage_accounts": false, "archive_season": false}'::jsonb
        END
    )
    ON CONFLICT (id) DO UPDATE SET user_id = EXCLUDED.user_id, username = EXCLUDED.username, email = EXCLUDED.email, name = EXCLUDED.name, phone = EXCLUDED.phone, role = EXCLUDED.role;

    RETURN new_user_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

GRANT EXECUTE ON FUNCTION public.admin_create_auth_user(TEXT, TEXT, TEXT, TEXT, TEXT, TEXT) TO anon, authenticated, service_role;

